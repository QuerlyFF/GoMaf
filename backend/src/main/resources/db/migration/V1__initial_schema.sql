-- Fresh installs create the full schema here. Existing pre-Flyway installations
-- are baselined at version 0, so this migration is deliberately idempotent.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) NOT NULL UNIQUE,
    username_key VARCHAR(32),
    password VARCHAR(100) NOT NULL,
    role VARCHAR(16) NOT NULL,
    avatar_data BYTEA,
    avatar_content_type VARCHAR(32),
    avatar_safety_version INTEGER,
    registration_ip_hash VARCHAR(64),
    credential_version INTEGER,
    games_played INTEGER NOT NULL,
    wins INTEGER NOT NULL,
    losses INTEGER NOT NULL,
    rating FLOAT(53) NOT NULL,
    average_score FLOAT(53) NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- Columns introduced by the hardened v8 line. Nullable additions are intentional
-- so an existing database can be upgraded before DataInitializer backfills values.
ALTER TABLE users ADD COLUMN IF NOT EXISTS username_key VARCHAR(32);
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_data BYTEA;
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_content_type VARCHAR(32);
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_safety_version INTEGER;
ALTER TABLE users ADD COLUMN IF NOT EXISTS registration_ip_hash VARCHAR(64);
ALTER TABLE users ADD COLUMN IF NOT EXISTS credential_version INTEGER;

CREATE TABLE IF NOT EXISTS news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS rules_page (
    id BIGINT PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    content TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS rules_import_state (
    id BIGINT PRIMARY KEY,
    version INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS game_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    scheduled_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    host VARCHAR(80) NOT NULL,
    description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    game_date DATE NOT NULL,
    host VARCHAR(80) NOT NULL,
    winner VARCHAR(16) NOT NULL,
    summary TEXT NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS game_players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL,
    user_id BIGINT,
    seat_number INTEGER NOT NULL,
    display_name VARCHAR(64) NOT NULL,
    role VARCHAR(16) NOT NULL,
    first_killed BOOLEAN NOT NULL,
    best_move1 INTEGER,
    best_move2 INTEGER,
    best_move3 INTEGER,
    victory_points NUMERIC(8,2) NOT NULL,
    first_killed_points NUMERIC(8,2) NOT NULL,
    best_move_points NUMERIC(8,2) NOT NULL,
    bonus_points NUMERIC(8,2) NOT NULL,
    penalty_points NUMERIC(8,2) NOT NULL,
    total_points NUMERIC(8,2) NOT NULL,
    won BOOLEAN NOT NULL,
    CONSTRAINT fk_game_players_game FOREIGN KEY (game_id) REFERENCES games(id),
    CONSTRAINT fk_game_players_user FOREIGN KEY (user_id) REFERENCES users(id)
);
