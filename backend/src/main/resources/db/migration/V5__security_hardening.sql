-- WP11-023 security hardening. V1-V4 are immutable.

CREATE TABLE security_rate_limit_buckets (
    bucket_key VARCHAR(96) PRIMARY KEY,
    attempts INTEGER NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_security_rate_limit_attempts CHECK (attempts >= 0)
);
CREATE INDEX idx_security_rate_limit_expiry ON security_rate_limit_buckets(expires_at);

CREATE TABLE admin_mfa_credentials (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    encrypted_secret VARCHAR(512) NOT NULL,
    enabled_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE admin_mfa_recovery_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    code_hash VARCHAR(100) NOT NULL,
    used_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_admin_mfa_recovery_user ON admin_mfa_recovery_codes(user_id, used_at);

CREATE TABLE security_sessions (
    session_hash VARCHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_name VARCHAR(16) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_security_session_role CHECK (role_name IN ('PLAYER','MODERATOR','ADMIN'))
);
CREATE INDEX idx_security_sessions_user_created ON security_sessions(user_id, created_at);
CREATE INDEX idx_security_sessions_expiry ON security_sessions(expires_at);

-- Fail closed instead of silently rewriting existing production data. The deploy preflight
-- performs the same compatibility check before migration; this is the database backstop.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM game_videos WHERE lower(url) NOT LIKE 'https://%') THEN
        RAISE EXCEPTION 'WP11-023 requires all existing game_videos URLs to use HTTPS';
    END IF;
END
$$;

ALTER TABLE game_videos
    ADD CONSTRAINT chk_game_videos_https
    CHECK (lower(url) LIKE 'https://%');
