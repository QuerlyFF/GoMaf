CREATE TABLE IF NOT EXISTS schedule_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_entry_id BIGINT NOT NULL REFERENCES game_schedule(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_schedule_participant UNIQUE(schedule_entry_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_schedule_participants_entry ON schedule_participants(schedule_entry_id);
CREATE INDEX IF NOT EXISTS idx_schedule_participants_user ON schedule_participants(user_id);

CREATE TABLE IF NOT EXISTS tournaments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    game_count INTEGER NOT NULL,
    participation_cost NUMERIC(10,2),
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_tournaments_game_count CHECK (game_count >= 1 AND game_count <= 1000),
    CONSTRAINT chk_tournaments_cost CHECK (participation_cost IS NULL OR participation_cost >= 0)
);

CREATE TABLE IF NOT EXISTS tournament_dates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    event_date DATE NOT NULL,
    position INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_tournament_date_position UNIQUE(tournament_id, position)
);
CREATE INDEX IF NOT EXISTS idx_tournament_dates_tournament ON tournament_dates(tournament_id);
CREATE INDEX IF NOT EXISTS idx_tournament_dates_date ON tournament_dates(event_date);

CREATE TABLE IF NOT EXISTS tournament_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    invited BOOLEAN NOT NULL DEFAULT FALSE,
    participating BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_tournament_participant UNIQUE(tournament_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_tournament_participants_tournament ON tournament_participants(tournament_id);
CREATE INDEX IF NOT EXISTS idx_tournament_participants_user ON tournament_participants(user_id);

