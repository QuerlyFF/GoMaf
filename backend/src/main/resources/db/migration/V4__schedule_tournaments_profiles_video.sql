-- v10.2: average_score now means average additional points only; victory points are excluded.
UPDATE users u
SET average_score = COALESCE((
    SELECT AVG(
        gp.first_killed_points
        + gp.best_move_points
        + gp.bonus_points
        - gp.penalty_points
    )
    FROM game_players gp
    WHERE gp.user_id = u.id
), 0)
WHERE u.account_role IN ('PLAYER', 'MODERATOR');
